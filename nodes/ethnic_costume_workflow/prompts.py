def join_prompt_sections(sections: list[tuple[str, str | None]]) -> str:
    lines = []
    for label, value in sections:
        if value is None:
            continue
        value = value.strip()
        if value:
            lines.append(f"{label}: {value}")
    return "\n".join(lines)
